func TestDisappearingSettingForMessageSkipsSavedMessages(t *testing.T) {
	sa := &SnapchatAPI{chatDisappearAfter: map[string]int64{"chat-1": 10}}
	got := sa.disappearingSettingForMessage("chat-1", sidecar.Message{
		ID:                    "m1",
		Text:                  "unsaved",
		DisappearAfterSeconds: 20,
	})
	if got.Timer != 20*time.Second {
		t.Fatalf("message disappearing timer = %s, want 20s", got.Timer)
	}
	got = sa.disappearingSettingForMessage("chat-1", sidecar.Message{
		ID:    "m2",
		Text:  "saved",
		Saved: true,
	})
	if got.Timer != 0 {
		t.Fatalf("saved message got disappearing timer %s", got.Timer)
	}
	got = sa.disappearingSettingForMessage("chat-1", sidecar.Message{
		ID:   "m3",
		Text: "chat default",
	})
	if got.Timer != 10*time.Second {
		t.Fatalf("chat disappearing timer = %s, want 10s", got.Timer)
	}
}
